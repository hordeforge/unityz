//! LZ4 block decompressor, implemented from the public LZ4 block format
//! specification.
//!
//! Unity's LZ4-compressed bundle blocks are plain LZ4 blocks: a sequence of
//! tokens, each carrying a literal run and an optional match referencing an
//! offset in the already-decompressed output. There is no frame header, no
//! block-size field, and no checksum — the uncompressed size comes from the
//! Unity bundle block table.
//!
//! Sequence layout (per token):
//!
//! ```text
//! token:           u8        high nibble = literal length (15 = extended),
//!                            low nibble  = match length - 4 (15 = extended)
//! literals:        token>>>4 bytes, plus 255-extension bytes when 15
//! offset:          u16 LE    1-based distance back into the output
//! match length:    low nibble + 4, plus 255-extension bytes when 15
//! ```
//!
//! The final sequence consists of literals only (no offset/match). Overlap
//! between a match and its source is legal (that is how runs like
//! `aaaaaa` are encoded), so matches are copied in `offset`-sized chunks.

const std = @import("std");

pub const Error = error{
    TruncatedInput,
    OutputOverflow,
    InvalidMatch,
    CorruptInput,
    OutOfMemory,
};

/// Decompresses an LZ4 block into a fresh `expected_size`-byte buffer.
pub fn decompress(allocator: std.mem.Allocator, src: []const u8, expected_size: usize) Error![]u8 {
    const out = allocator.alloc(u8, expected_size) catch return error.OutputOverflow;
    errdefer allocator.free(out);
    try decompressInto(out, src);
    return out;
}

/// Decompresses an LZ4 block into `out`, which must be exactly the block's
/// decompressed size. Lets a caller that already owns the destination -
/// a bundle decoding blocks straight into the concatenated stream - skip
/// both the per-block allocation and the copy out of it.
pub fn decompressInto(out: []u8, src: []const u8) Error!void {
    const expected_size = out.len;

    var in_pos: usize = 0;
    var out_pos: usize = 0;

    while (true) {
        // A block ends either when the final sequence was literals-only
        // (the `in_pos == src.len` check after the literal copy) or when a
        // match consumed the last of the input.
        if (in_pos > src.len) return error.TruncatedInput;
        if (in_pos == src.len) break;
        const token = src[in_pos];
        in_pos += 1;

        // --- literal run ---
        var lit_len: usize = token >> 4;
        if (lit_len == 15) {
            lit_len += try readExtension(&in_pos, src);
        }
        if (lit_len > expected_size -| out_pos) return error.OutputOverflow;
        if (in_pos + lit_len > src.len) return error.TruncatedInput;
        @memcpy(out[out_pos .. out_pos + lit_len], src[in_pos .. in_pos + lit_len]);
        in_pos += lit_len;
        out_pos += lit_len;

        // End of block: the last sequence never carries a match.
        if (in_pos == src.len) break;

        // --- match ---
        if (in_pos + 2 > src.len) return error.TruncatedInput;
        const offset: usize = @as(usize, src[in_pos]) | (@as(usize, src[in_pos + 1]) << 8);
        in_pos += 2;
        if (offset == 0 or offset > out_pos) return error.InvalidMatch;

        var match_len: usize = token & 0x0f;
        if (match_len == 15) {
            match_len += try readExtension(&in_pos, src);
        }
        match_len += 4;
        if (match_len > expected_size -| out_pos) return error.OutputOverflow;

        // Copy in `offset`-sized chunks: each chunk reads only bytes an
        // earlier chunk already wrote, so an overlapping match (LZ4's run
        // idiom) still works, while the common non-overlapping case becomes
        // a single memcpy instead of a byte-at-a-time loop.
        var remaining = match_len;
        while (remaining != 0) {
            const chunk = @min(remaining, offset);
            @memcpy(out[out_pos..][0..chunk], out[out_pos - offset ..][0..chunk]);
            out_pos += chunk;
            remaining -= chunk;
        }
    }

    if (out_pos != expected_size) return error.OutputOverflow;
}

/// Reads the 255-extension of a length field. Returns the accumulated extra
/// length beyond the first 15.
fn readExtension(in_pos: *usize, src: []const u8) Error!usize {
    var extra: usize = 0;
    while (true) {
        if (in_pos.* >= src.len) return error.TruncatedInput;
        const b = src[in_pos.*];
        in_pos.* += 1;
        extra += b;
        if (b != 255) break;
    }
    return extra;
}

test "decompress literals only" {
    const a = std.testing.allocator;
    // token 0x40 = 4 literals, no match; then "abcd"
    const out = try decompress(a, "\x40abcd", 4);
    defer a.free(out);
    try std.testing.expectEqualStrings("abcd", out);
}

test "decompress literals then end" {
    const a = std.testing.allocator;
    // empty input decodes to zero bytes
    const out = try decompress(a, "\x00", 0);
    defer a.free(out);
    try std.testing.expectEqual(@as(usize, 0), out.len);
}

test "decompress single match" {
    const a = std.testing.allocator;
    // "ab" + match len 6 (2<<... ) at offset 2 → "abababab"
    // token 0x22 = 2 literals, match length 6 (low nibble 2 + 4)
    const out = try decompress(a, "\x22ab\x02\x00", 8);
    defer a.free(out);
    try std.testing.expectEqualStrings("abababab", out);
}

test "decompress run with overlapping match" {
    const a = std.testing.allocator;
    // literal 'x', then match length 9 at offset 1 → 'x' + 9 'x's
    // token 0x15 = 1 literal, match length 5+4=9; offset 1
    const out = try decompress(a, "\x15x\x01\x00", 10);
    defer a.free(out);
    try std.testing.expectEqualStrings("xxxxxxxxxx", out);
}

test "decompress extended literal length" {
    const a = std.testing.allocator;
    // 20 literals: token 0xF0 (15<<4), extension byte 5, then 20 bytes
    const payload = "abcdefghijklmnopqrst"; // 20 bytes
    var src: std.ArrayList(u8) = .empty;
    defer src.deinit(a);
    try src.append(a, 0xF0);
    try src.append(a, 5);
    try src.appendSlice(a, payload);
    const out = try decompress(a, src.items, 20);
    defer a.free(out);
    try std.testing.expectEqualStrings(payload, out);
}

test "decompress extended match length" {
    const a = std.testing.allocator;
    // literal 'a', match len 4+15+3=22 at offset 1
    // token 0x1F = 1 literal, match nibble 15 → extension 3
    var src: std.ArrayList(u8) = .empty;
    defer src.deinit(a);
    try src.append(a, 0x1F);
    try src.append(a, 'a');
    try src.appendSlice(a, &.{ 0x01, 0x00 });
    try src.append(a, 3); // match extension
    const out = try decompress(a, src.items, 23);
    defer a.free(out);
    try std.testing.expectEqualStrings("aaaaaaaaaaaaaaaaaaaaaaa", out);
}

test "decompress errors" {
    const a = std.testing.allocator;
    // offset 0 is invalid
    try std.testing.expectError(error.InvalidMatch, decompress(a, "\x11a\x00\x00", 5));
    // offset beyond output start is invalid
    try std.testing.expectError(error.InvalidMatch, decompress(a, "\x11a\x05\x00", 5));
    // truncated input
    try std.testing.expectError(error.TruncatedInput, decompress(a, "\x22ab\x02", 8));
    // output size mismatch (decode yields fewer bytes than declared)
    try std.testing.expectError(error.OutputOverflow, decompress(a, "\x40abcd", 5));
}

/// Compresses `src` into a fresh LZ4 block (no frame header, no checksum -
/// the inverse of `decompress`). Greedy hash-table matcher: every 4-byte
/// window hashes into a table of the most recent position, and a candidate
/// within the u16 offset range (<= 65535) is extended into a match of at
/// least 4 bytes. Literal runs are always emitted, so the output is
/// self-describing; worst case is `src.len + src.len/255 + 16` bytes.
pub fn compress(allocator: std.mem.Allocator, src: []const u8) Error![]u8 {
    if (src.len == 0) return allocator.alloc(u8, 0);
    // A literal-only block costs two overhead bytes per 270 literals (one
    // token byte with a 255 extension byte), so bound generously.
    const worst = src.len + src.len / 128 + 32;
    const out = allocator.alloc(u8, worst) catch return error.OutputOverflow;
    errdefer allocator.free(out);

    // 12-bit hash of the last 4 bytes seen at each position; 1-based so 0
    // means "no candidate yet".
    var table = [_]u32{0} ** 4096;
    var opos: usize = 0;
    var i: usize = 0;
    var lit_start: usize = 0;

    const hash4 = struct {
        fn at(s: []const u8, pos: usize) u32 {
            const x = @as(u32, s[pos]) | (@as(u32, s[pos + 1]) << 8) | (@as(u32, s[pos + 2]) << 16) | (@as(u32, s[pos + 3]) << 24);
            return (x *% 2654435761) >> 20; // 0..4095
        }
    }.at;

    // Matches only start at least MFLIMIT (12) bytes before the end; the
    // trailing region is written as the final literals-only sequence.
    while (i + 12 <= src.len) : (i += 1) {
        const h = hash4(src, i);
        const cand = table[h];
        table[h] = @intCast(i + 1);
        if (cand == 0 or i + 1 - cand > 65535) continue;
        const c: usize = @intCast(cand - 1);
        // Extend the match; overlap with the source is fine (runs).
        var m: usize = 0;
        while (i + m < src.len and src[c + m] == src[i + m]) : (m += 1) {}
        // End-of-block conditions (lz4_Block_format.md): the last match
        // must end at least LASTLITERALS (5) bytes before the end, leaving
        // a literals-only final sequence of at least 5 bytes. Blocks where
        // the final sequence is shorter are rejected by strict decoders
        // (the C reference and python-lz4).
        if (i + m > src.len - 5) m = src.len - 5 - i;
        if (m < 4) continue;
        // Emit the literal run then the match.
        const lit_len = i - lit_start;
        const lit_nib: u8 = if (lit_len >= 15) 15 else @intCast(lit_len);
        const match_nib: u8 = if (m - 4 >= 15) 15 else @intCast(m - 4);
        const token: u8 = (lit_nib << 4) | match_nib;
        out[opos] = token;
        opos += 1;
        if (lit_len >= 15) {
            var rest = lit_len - 15;
            while (rest >= 255) : (rest -= 255) {
                out[opos] = 255;
                opos += 1;
            }
            out[opos] = @intCast(rest);
            opos += 1;
        }
        @memcpy(out[opos .. opos + lit_len], src[lit_start..i]);
        opos += lit_len;
        const dist: u16 = @intCast(i - c);
        out[opos] = @intCast(dist & 0xff);
        out[opos + 1] = @intCast(dist >> 8);
        opos += 2;
        if (m - 4 >= 15) {
            var rest = m - 4 - 15;
            while (rest >= 255) : (rest -= 255) {
                out[opos] = 255;
                opos += 1;
            }
            out[opos] = @intCast(rest);
            opos += 1;
        }
        i += m - 1; // the loop's own +1 lands on the byte after the match
        lit_start = i + 1;
    }

    // Trailing literals-only sequence.
    const lit_len = src.len - lit_start;
    if (lit_len > 0) {
        const lit_nib: u8 = if (lit_len >= 15) 15 else @intCast(lit_len);
        out[opos] = lit_nib << 4;
        opos += 1;
        if (lit_len >= 15) {
            var rest = lit_len - 15;
            while (rest >= 255) : (rest -= 255) {
                out[opos] = 255;
                opos += 1;
            }
            out[opos] = @intCast(rest);
            opos += 1;
        }
        @memcpy(out[opos .. opos + lit_len], src[lit_start..]);
        opos += lit_len;
    }

    std.debug.assert(opos <= worst);
    // Shrink to the exact output size; the caller frees the returned slice,
    // so its length must match the allocation.
    return allocator.realloc(out, opos);
}

