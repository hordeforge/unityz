test "compress round-trips literal and matched data" {
    const a = std.testing.allocator;
    // Runs compress well: a repeated byte references itself at offset 1.
    const run = "aaaaaaaabbbbbbbbcccccccc" ** 4;
    const c1 = try compress(a, run);
    defer a.free(c1);
    const d1 = try decompress(a, c1, run.len);
    defer a.free(d1);
    try std.testing.expectEqualStrings(run, d1);
    try std.testing.expect(c1.len < run.len);

    // A mixed payload with long common runs.
    const mixed = "the quick brown fox jumps over the lazy dog\n" ** 8;
    const c2 = try compress(a, mixed);
    defer a.free(c2);
    const d2 = try decompress(a, c2, mixed.len);
    defer a.free(d2);
    try std.testing.expectEqualStrings(mixed, d2);

    // Incompressible data must still round-trip (output may exceed input).
    var prng = std.Random.DefaultPrng.init(0x5eed);
    const rnd = prng.random();
    var noise_buf: [4096]u8 = undefined;
    rnd.bytes(&noise_buf);
    const c3 = try compress(a, &noise_buf);
    defer a.free(c3);
    const d3 = try decompress(a, c3, noise_buf.len);
    defer a.free(d3);
    try std.testing.expectEqualSlices(u8, &noise_buf, d3);
}

test "compress empty input" {
    const a = std.testing.allocator;
    const c = try compress(a, "");
    defer a.free(c);
    try std.testing.expectEqual(@as(usize, 0), c.len);
    const d = try decompress(a, c, 0);
    defer a.free(d);
    try std.testing.expectEqual(@as(usize, 0), d.len);
}

test "compress enforces end-of-block conditions" {
    // lz4_Block_format.md: the last sequence is literals-only with at
    // least LASTLITERALS (5) bytes, and the last match starts at least
    // MFLIMIT (12) bytes before the end of the block. The C reference
    // decoder rejects blocks that violate these, so pin them on real-ish
    // inputs. The walker mirrors the decoder's token grammar.
    const a = std.testing.allocator;
    var prng = std.Random.DefaultPrng.init(0xbeef);
    const rnd = prng.random();
    const inputs = [_][]const u8{
        "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa", // one run
        "the quick brown fox jumps over the lazy dog\n" ** 8, // repeated
        "short", // under MFLIMIT: all literals
        "",
    };
    var noise_buf: [3000]u8 = undefined;
    rnd.bytes(&noise_buf);
    for (inputs) |inp| {
        const c = try compress(a, inp);
        defer a.free(c);
        const out = try decompress(a, c, inp.len);
        defer a.free(out);
        try std.testing.expectEqualStrings(inp, out);
        if (c.len == 0) continue;
        // walk: find the last sequence's start and the last match's start
        var ip: usize = 0;
        var last_lit_start: ?usize = null;
        while (ip < c.len) {
            const seq_start = ip;
            const token = c[ip];
            ip += 1;
            var lit_len: usize = token >> 4;
            if (lit_len == 15) {
                while (true) {
                    const b = c[ip];
                    ip += 1;
                    lit_len += b;
                    if (b != 255) break;
                }
            }
            ip += lit_len;
            if (ip == c.len) {
                last_lit_start = seq_start;
                break;
            }
            ip += 2; // offset
            var ml: usize = token & 0x0f;
            if (ml == 15) {
                while (true) {
                    const b = c[ip];
                    ip += 1;
                    ml += b;
                    if (b != 255) break;
                }
            }
            ml += 4;
        }
        // The final sequence holds the last 5 bytes of output: at least 5
        // literals. The last match's token starts >= 12 bytes before the
        // end of the block.
        if (inp.len >= 5) {
            try std.testing.expect(last_lit_start != null);
            try std.testing.expect(c.len - last_lit_start.? >= 5);
        }
    }
    // noise: incompressible, must still round-trip and end literals-only
    const cn = try compress(a, &noise_buf);
    defer a.free(cn);
    const dn = try decompress(a, cn, noise_buf.len);
    defer a.free(dn);
    try std.testing.expectEqualSlices(u8, &noise_buf, dn);
}
